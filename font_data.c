// 当找不到字模时，返回一个 12x12 的空心小方框，而不是任由屏幕乱画
static const unsigned char font_missing_glyph[24] = {
    0xFF,0xF0, 0x80,0x10, 0x80,0x10, 0x80,0x10, 0x80,0x10, 0x80,0x10,
    0x80,0x10, 0x80,0x10, 0x80,0x10, 0x80,0x10, 0x80,0x10, 0xFF,0xF0
};


// =====================================================================
// 4. 字模查找核心函数 (二分查找)
// =====================================================================
// 获取中文字模数据的函数
const unsigned char* font_get_chinese(unsigned short unicode) {
    int left = 0;
    int right = (sizeof(chinese_font_table) / sizeof(chinese_font_table[0])) - 1;
    int mid;

    while (left <= right) {
        mid = left + (right - left) / 2;
        if (chinese_font_table[mid].unicode == unicode) {
            return chinese_font_table[mid].data; // 查找到，返回对应字模
        } else if (chinese_font_table[mid].unicode < unicode) {
            left = mid + 1;
        } else {
            right = mid - 1;
        }
    }
    
    // 如果走到这里，说明找不到该汉字。
    // 返回缺省方框字模，这样屏幕上会显示一个"口"，而不是满屏乱码
    return font_missing_glyph; 
}

