bool font_get_chinese(uint16_t unicode, uint8_t data[32]) {
    int left = 0;
    int right = (sizeof(chinese_font_table) / sizeof(chinese_font_table[0])) - 1;

    while (left <= right) {
        int mid = left + (right - left) / 2;
        if (chinese_font_table[mid].unicode == unicode) {
            memcpy(data, chinese_font_table[mid].data, 32);
            return true;
        } else if (chinese_font_table[mid].unicode < unicode) {
            left = mid + 1;
        } else {
            right = mid - 1;
        }
    }

    memcpy(data, font_missing_glyph, 32);
    return false;
}
