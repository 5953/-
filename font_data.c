#define CHINESE_FONT_COUNT (sizeof(chinese_font_table) / sizeof(chinese_font_12x12_t))

// 二分查找汉字
bool font_get_chinese(uint16_t unicode, uint8_t data[24]) {
    int left = 0;
    int right = CHINESE_FONT_COUNT - 1;
    
    while (left <= right) {
        int mid = (left + right) / 2;
        if (chinese_font_table[mid].unicode == unicode) {
            memcpy(data, chinese_font_table[mid].data, 24);
            return true;
        } else if (chinese_font_table[mid].unicode < unicode) {
            left = mid + 1;
        } else {
            right = mid - 1;
        }
    }
    
    // 未找到，返回空方块（表示缺字）
    memset(data, 0, 24);
    data[0] = 0xFF; data[1] = 0xF0;
    data[2] = 0x80; data[3] = 0x10;
    for (int i = 4; i < 20; i += 2) {
        data[i] = 0x80;
        data[i+1] = 0x10;
    }
    data[20] = 0x80; data[21] = 0x10;
    data[22] = 0xFF; data[23] = 0xF0;
    
    return false;
}
